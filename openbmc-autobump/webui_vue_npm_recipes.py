HEADER = (
    "# Generated by openbmc-autobump from the webui-vue package-lock.json.\n"
    "# Do not edit. A webui-vue SRCREV bump regenerates this file.\n"
)

PN_PREFIX = "webui-vue-npm-"

INC_NAME = "webui-vue-npm.inc"

# vite build's own tools. Every package vite.config.js imports joins these
# when the config is given. Their dependency closure is the offline
# toolchain. Lint, unit test, and docs packages are not included.
TOOLCHAIN_ROOTS = (
    "vite",
    "@vitejs/plugin-basic-ssl",
    "@vitejs/plugin-vue",
    "sass",
    "vite-plugin-compression",
    "vite-svg-loader",
)

NODE_BUILTINS = frozenset(
    (
        "assert async_hooks buffer child_process cluster console crypto "
        "dgram dns events fs http http2 https inspector module net os path "
        "perf_hooks process querystring readline stream string_decoder "
        "timers tls tty url util v8 vm worker_threads zlib"
    ).split()
)

_IMPORT_FROM = re.compile(
    r"(?<![\w$.@])import\s+(?:[^'\";]*?\s+from\s+)?['\"]([^'\"]+)['\"]"
)
_IMPORT_CALL = re.compile(
    r"(?<![\w$.@])(?:import|require)\s*\(\s*['\"]([^'\"]+)['\"]\s*\)"
)

# OpenBMC builds webui-vue on a glibc x86_64 host. darwin, win32, musl,
# and other CPU packages are not fetched.
DEFAULT_BUILD_OS = "linux"
DEFAULT_BUILD_CPU = "x64"
DEFAULT_BUILD_LIBC = "gnu"

# npm's spelling of the libc values above.
NPM_LIBC = {"gnu": "glibc", "musl": "musl"}

