def npm_name_from_lock_path(lock_path):
    """Return the npm name for a lockfile packages key."""
    if "/node_modules/" not in "/{}/".format(lock_path):
        raise ValueError("not an npm package path: {}".format(lock_path))
    name = lock_path.split("node_modules/")[-1].strip("/")
    if not name:
        raise ValueError("empty npm package name in {}".format(lock_path))
    return name


def recipe_pn(npm_name):
    """Bitbake package name for an npm package.

    bitbake splits recipe file names on "_", so "@types/babel__core"
    becomes types-babel--core.
    """
    sanitized = npm_name[1:] if npm_name.startswith("@") else npm_name
    sanitized = sanitized.replace("/", "-").replace("_", "-").lower()
    if not re.fullmatch(r"[a-z0-9.+-]+", sanitized):
        raise ValueError(
            "npm name is not a valid recipe name: {}".format(npm_name)
        )
    return PN_PREFIX + sanitized


def version_key(version):
    items = []
    for piece in re.split(r"[.-]", version):
        if piece.isdigit():
            items.append((0, int(piece)))
        else:
            items.append((1, piece))
    return items


def parse_integrity(integrity):
    """Return (algo, hex) for the checksum bitbake should verify.

    A multi-hash string prefers sha512. A sha1-only string is accepted.
    """
    sha512 = None
    sha1 = None
    for part in integrity.split():
        algo, sep, digest = part.partition("-")
        if sep != "-" or not digest:
            raise ValueError("unsupported integrity: {}".format(integrity))
        try:
            raw = base64.b64decode(digest, validate=True)
        except Exception as exc:
            raise ValueError("bad integrity: {}".format(integrity)) from exc
        if algo == "sha512" and len(raw) == 64:
            sha512 = raw.hex()
        elif algo == "sha1" and len(raw) == 20:
            sha1 = raw.hex()
        else:
            raise ValueError("unsupported integrity: {}".format(integrity))
    if sha512:
        return "sha512", sha512
    if sha1:
        return "sha1", sha1
    raise ValueError("unsupported integrity: {}".format(integrity))


def yocto_license(spdx_expression):
    """Turn an SPDX license expression into bitbake LICENSE syntax.

    ``Apache-2.0 WITH LLVM-exception`` becomes
    ``Apache-2.0-with-LLVM-exception``. ``OR`` becomes ``|`` and
    ``AND`` becomes ``&``.
    """
    text = spdx_expression.strip()
    previous = None
    while previous != text:
        previous = text
        text = re.sub(
            r"([A-Za-z0-9.+-]+)\s+WITH\s+([A-Za-z0-9.+-]+)",
            r"\1-with-\2",
            text,
        )
    text = re.sub(r"\bOR\b", "|", text)
    text = re.sub(r"\bAND\b", "&", text)
    return text


def spdx_license_ids(spdx_expression):
    """Return license ids after WITH has been joined into one id."""
    text = spdx_expression.strip()
    previous = None
    while previous != text:
        previous = text
        text = re.sub(
            r"([A-Za-z0-9.+-]+)\s+WITH\s+([A-Za-z0-9.+-]+)",
            r"\1-with-\2",
            text,
        )
    parts = re.split(r"\bOR\b|\bAND\b|[()]", text)
    ids = [part.strip() for part in parts if part.strip()]
    if not ids:
        raise ValueError("no license id in {}".format(spdx_expression))
    return ids


def _platform_matches(value, wanted):
    """npm's os, cpu, and libc test, including "!" negation."""
    if isinstance(wanted, str):
        wanted = [wanted]
    if wanted == ["any"]:
        return True
    if "!" + value in wanted:
        return False
    listed = [entry for entry in wanted if not entry.startswith("!")]
    return not listed or value in listed


def matches_build_host(meta, npm_name, build_os, build_cpu, build_libc):
    """False for platform binaries built for another OS, CPU, or libc.

    Entries without os or cpu are portable. Lockfiles often omit libc, so
    glibc and musl builds of a platform binary are also told apart by name.
    """
    wanted_os = meta.get("os")
    wanted_cpu = meta.get("cpu")
    if wanted_os and not _platform_matches(build_os, wanted_os):
        return False
    if wanted_cpu and not _platform_matches(build_cpu, wanted_cpu):
        return False
    if meta.get("libc"):
        return _platform_matches(NPM_LIBC[build_libc], meta["libc"])
    if not wanted_os and not wanted_cpu:
        return True
    lowered = npm_name.lower()
    if "musl" in lowered:
        return build_libc == "musl"
    if "glibc" in lowered or "-gnu" in lowered:
        return build_libc == "gnu"
    return True


def resolve_package(parent, name, packages):
    """Node resolution of name starting at a lockfile package key."""
    current = parent
    while True:
        candidate = "node_modules/" + name
        if current:
            candidate = current + "/" + candidate
        if candidate in packages:
            return candidate
        if not current:
            return None
        if "/node_modules/" in current:
            current = current.rsplit("/node_modules/", 1)[0]
        elif current.startswith("node_modules/"):
            current = ""
        else:
            return None


def _edges(meta):
    """Names of the packages a lockfile entry needs installed.

    Optional peers are skipped. npm never installs them on their own, so
    following them pulls in tools that only some other package wanted.
    """
    optional_peers = {
        name
        for name, info in (meta.get("peerDependenciesMeta") or {}).items()
        if info.get("optional")
    }
    names = list(meta.get("dependencies") or {})
    names += list(meta.get("optionalDependencies") or {})
    names += [
        name
        for name in meta.get("peerDependencies") or {}
        if name not in optional_peers
    ]
    return names


def _walk(roots, packages, include_dev, host):
    seen = []
    seen_keys = set()
    queue = []
    for name in roots:
        key = resolve_package("", name, packages)
        if key:
            queue.append(key)
    while queue:
        key = queue.pop(0)
        if key in seen_keys:
            continue
        seen_keys.add(key)
        meta = packages.get(key) or {}
        if meta.get("link"):
            continue
        if not include_dev and (meta.get("dev") or meta.get("devOptional")):
            continue
        name = npm_name_from_lock_path(key)
        if not matches_build_host(meta, name, *host):
            continue
        seen.append(key)
        for dep_name in _edges(meta):
            child = resolve_package(key, dep_name, packages)
            if child and child not in seen_keys:
                queue.append(child)
    return seen


def config_imports(text):
    """npm packages a Vite config imports, by package name."""
    text = re.sub(r"(^|\s)/\*.*?\*/", r"\1", text, flags=re.S)
    text = re.sub(r"(^|\s)//.*$", r"\1", text, flags=re.M)
    names = set()
    for specifier in _IMPORT_FROM.findall(text) + _IMPORT_CALL.findall(text):
        if specifier.startswith((".", "/", "@/", "node:", "virtual:")):
            continue
        parts = specifier.split("/")
        name = "/".join(parts[:2]) if specifier.startswith("@") else parts[0]
        if name not in NODE_BUILTINS:
            names.add(name)
    return sorted(names)


def toolchain_roots(lock, vite_config=None):
    """TOOLCHAIN_ROOTS plus every package vite_config imports.

    An import that package-lock.json does not install raises, because the
    offline build could not load the config.
    """
    roots = set(TOOLCHAIN_ROOTS)
    if vite_config:
        packages = lock.get("packages", {})
        for name in config_imports(vite_config):
            if "node_modules/" + name not in packages:
                raise ValueError(
                    "vite.config.js imports {}, which package-lock.json "
                    "does not install".format(name)
                )
            roots.add(name)
    return tuple(sorted(roots))


def select_packages(
    lock,
    build_os=DEFAULT_BUILD_OS,
    build_cpu=DEFAULT_BUILD_CPU,
    build_libc=DEFAULT_BUILD_LIBC,
    roots=TOOLCHAIN_ROOTS,
):
    """Return shipped and build-only lockfile keys.

    Shipped packages are walked from the root ``dependencies``, skipping
    dev and devOptional entries. The toolchain walk starts at roots and
    includes dev-only entries. A package that is in both walks is shipped.
    """
    packages = lock.get("packages", {})
    root = packages.get("", {})
    host = (build_os, build_cpu, build_libc)
    shipped = _walk(root.get("dependencies") or {}, packages, False, host)
    toolchain = _walk(roots, packages, True, host)
    shipped_set = set(shipped)
    build_only = [key for key in toolchain if key not in shipped_set]
    return shipped, build_only


def _group_entries(keys, packages):
    grouped = {}
    order = []
    for lock_path in keys:
        meta = packages[lock_path]
        npm_name = npm_name_from_lock_path(lock_path)
        version = meta.get("version")
        resolved = meta.get("resolved")
        integrity = meta.get("integrity")
        if not version or not resolved or not integrity:
            raise ValueError(
                "{} is missing version, resolved, or integrity".format(
                    lock_path
                )
            )
        if not re.fullmatch(r"[0-9A-Za-z.+-]+", version):
            raise ValueError(
                "{} version is not a valid PV: {}".format(lock_path, version)
            )
        key = (npm_name, version)
        if key not in grouped:
            algo, digest = parse_integrity(integrity)
            grouped[key] = {
                "npm_name": npm_name,
                "version": version,
                "resolved": resolved,
                "integrity": integrity,
                "checksum_algo": algo,
                "checksum": digest,
                "lock_paths": [],
            }
            order.append(key)
        else:
            current = grouped[key]
            if (
                current["resolved"] != resolved
                or current["integrity"] != integrity
            ):
                raise ValueError(
                    "{} does not match the other {}@{} entries".format(
                        lock_path, npm_name, version
                    )
                )
        grouped[key]["lock_paths"].append(lock_path)
    return grouped, order


def _assign_names(grouped):
    by_name = {}
    for (npm_name, version), package in grouped.items():
        by_name.setdefault(npm_name, {})[version] = package
    for npm_name, versions in by_name.items():
        top = "node_modules/" + npm_name
        bare_version = None
        for version, package in versions.items():
            if top in package["lock_paths"]:
                bare_version = version
                break
        if bare_version is None:
            bare_version = max(versions, key=version_key)
        for version, package in versions.items():
            pn = recipe_pn(npm_name)
            if version != bare_version:
                pn = "{}-{}".format(pn, version)
            package["pn"] = pn
            package["lock_paths"].sort()


def collect_packages(
    lock, build_os, build_cpu, build_libc, roots=TOOLCHAIN_ROOTS
):
    packages_map = lock.get("packages", {})
    shipped_keys, build_keys = select_packages(
        lock, build_os, build_cpu, build_libc, roots
    )
    roles = {key: "shipped" for key in shipped_keys}
    for key in build_keys:
        roles[key] = "build"
    grouped, order = _group_entries(
        list(shipped_keys) + list(build_keys), packages_map
    )
    for package in grouped.values():
        roles_for_paths = {roles[path] for path in package["lock_paths"]}
        package["role"] = (
            "shipped" if "shipped" in roles_for_paths else "build"
        )
    _assign_names(grouped)
    seen_pn = {}
    collected = []
    for key in order:
        package = grouped[key]
        pn = package["pn"]
        if pn in seen_pn:
            raise ValueError(
                "{} and {} share recipe name {}".format(
                    seen_pn[pn], package["lock_paths"][0], pn
                )
            )
        seen_pn[pn] = package["lock_paths"][0]
        collected.append(package)
    return collected


def npm_recipe_dir(recipe):
    """Directory for generated recipes, beside the webui recipe dir.

    ``recipes-phosphor/webui/webui-vue_git.bb`` becomes
    ``recipes-phosphor/webui-vue-npm``. meta-phosphor only parses
    ``recipes-*/*/*.bb``, so the directory must not be nested deeper.
    """
    parent = os.path.dirname(recipe)
    if os.path.basename(parent) != "webui":
        raise ValueError(
            "webui-vue recipe is not under a webui directory: {}".format(
                recipe
            )
        )
    return os.path.join(os.path.dirname(parent), "webui-vue-npm")


def find_common_licenses(checkout):
    """Locate oe-core's common-licenses inside an openbmc checkout."""
    for relative in COMMON_LICENSE_DIRS:
        candidate = os.path.join(checkout, relative)
        if os.path.isdir(candidate):
            return candidate
    raise ValueError(
        "common-licenses not found in {}; expected {}".format(
            checkout, COMMON_LICENSE_DIRS[0]
        )
    )


def default_fetch(url):
    with urllib.request.urlopen(
        url, timeout=FETCH_TIMEOUT_SECONDS
    ) as response:
        return response.read()


def _member_bytes(archive, member):
    handle = archive.extractfile(member)
    if handle is None:
        raise ValueError("cannot read {}".format(member.name))
    with handle:
        return handle.read()


def _license_rank(name):
    """Lower is a better license-file name. None is not a license file."""
    if name in LICENSE_FILE_NAMES:
        return LICENSE_FILE_NAMES.index(name)
    upper = name.upper()
    if upper.startswith("LICENSE") or upper.startswith("LICENCE"):
        return 100 + len(name)
    if upper.startswith("COPYING"):
        return 200 + len(name)
    return None


def inspect_tarball(payload, integrity):
    """Check integrity and return license name plus an optional license file."""
    algo, digest = parse_integrity(integrity)
    hasher = hashlib.new(algo)
    hasher.update(payload)
    if hasher.hexdigest() != digest:
        raise ValueError("tarball does not match {}".format(integrity))
    with tarfile.open(fileobj=io.BytesIO(payload), mode="r:gz") as archive:
        package_json = None
        root = None
        for member in archive.getmembers():
            parts = [
                part for part in member.name.split("/") if part and part != "."
            ]
            if len(parts) == 2 and parts[1] == "package.json":
                package_json = member
                root = parts[0]
                break
        if package_json is None:
            raise ValueError("tarball has no package.json")
        meta = json.loads(_member_bytes(archive, package_json).decode("utf-8"))
        license_value = meta.get("license")
        if isinstance(license_value, dict):
            license_value = license_value.get("type")
        if not isinstance(license_value, str) or not license_value.strip():
            raise ValueError("tarball package.json has no license")
        license_value = license_value.strip()
        upper = license_value.upper()
        if "SEE LICENSE" in upper or upper.startswith("UNLICENSED"):
            raise ValueError("unsupported license: {}".format(license_value))
        found = {}
        for member in archive.getmembers():
            parts = [
                part for part in member.name.split("/") if part and part != "."
            ]
            if len(parts) != 2 or parts[0] != root or not member.isfile():
                continue
            if _license_rank(parts[1]) is None:
                continue
            found[parts[1]] = member
        license_file = None
        license_bytes = None
        if found:
            license_file = min(found, key=_license_rank)
            license_bytes = _member_bytes(archive, found[license_file])
    return license_value, license_file, license_bytes


def common_license_md5(common_licenses, spdx_id):
    path = os.path.join(common_licenses, spdx_id)
    if not os.path.isfile(path):
        raise ValueError("no common license file for {}".format(spdx_id))
    digest = hashlib.md5()
    with open(path, "rb") as handle:
        digest.update(handle.read())
    return digest.hexdigest()


def _checksum_lines(package, common_licenses):
    if package.get("license_file"):
        digest = hashlib.md5(package["license_bytes"]).hexdigest()
        return "file://{};md5={}".format(package["license_file"], digest)
    lines = []
    for spdx_id in spdx_license_ids(package["license"]):
        digest = common_license_md5(common_licenses, spdx_id)
        lines.append(
            "file://${{COMMON_LICENSE_DIR}}/{};md5={}".format(spdx_id, digest)
        )
    return " \\\n                    ".join(lines)


def purl(npm_name, version):
    """Package URL for an npm package. The scope's @ is encoded as %40."""
    if npm_name.startswith("@"):
        npm_name = "%40" + npm_name[1:]
    return "pkg:npm/{}@{}".format(npm_name, version)


def render_recipe(package, common_licenses):
    lic_files = _checksum_lines(package, common_licenses)
    lines = [
        HEADER.rstrip("\n"),
        "# npm package: {npm_name}@{version}".format(**package),
        "",
        'SUMMARY = "npm package {npm_name}"'.format(**package),
        'HOMEPAGE = "https://www.npmjs.com/package/{npm_name}"'.format(
            **package
        ),
        'LICENSE = "{}"'.format(yocto_license(package["license"])),
        'LIC_FILES_CHKSUM = "{}"'.format(lic_files),
        'SPDX_PACKAGE_URLS:prepend = "{} "'.format(
            purl(package["npm_name"], package["version"])
        ),
        'WEBUI_VUE_NPM_ROLE = "{role}"'.format(**package),
        'SPDX_CUSTOM_ANNOTATION_VARS:append = " WEBUI_VUE_NPM_ROLE"',
        "",
        "inherit allarch",
        "",
        'NPM_PACKAGE = "{npm_name}"'.format(**package),
        'NPM_VERSION = "{version}"'.format(**package),
        'NPM_LOCK_PATHS = "\\',
    ]
    for lock_path in package["lock_paths"]:
        lines.append("    {} \\".format(lock_path))
    lines.extend(
        [
            '"',
            "",
            (
                "SRC_URI = "
                '"{resolved};downloadfilename=${{BPN}}-${{PV}}.tgz;'
                'subdir=${{BPN}};striplevel=1"'
            ).format(**package),
            'SRC_URI[{}sum] = "{}"'.format(
                package["checksum_algo"], package["checksum"]
            ),
            "",
            'S = "${UNPACKDIR}/${BPN}"',
            "",
            'do_configure[noexec] = "1"',
            'do_compile[noexec] = "1"',
            'INHIBIT_SYSROOT_STRIP = "1"',
            "",
            "do_install() {",
            "\tfor path in ${NPM_LOCK_PATHS}; do",
            '\t\tinstall -d "${D}/sysroot-only/webui-vue/${path}"',
            '\t\tcp -R "${S}/." "${D}/sysroot-only/webui-vue/${path}/"',
            "\tdone",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def generator_id():
    """Hash of this file, so a generator change forces regeneration."""
    with open(os.path.abspath(__file__), "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()[:16]


def generation_inputs(lock_bytes, roots, build_os, build_cpu, build_libc):
    """Values recorded in the .inc. A bump regenerates when one changes."""
    return (
        ("WEBUI_VUE_NPM_LOCK_SHA256", hashlib.sha256(lock_bytes).hexdigest()),
        (
            "WEBUI_VUE_NPM_BUILD_HOST",
            "{}-{}-{}".format(build_os, build_cpu, build_libc),
        ),
        ("WEBUI_VUE_NPM_TOOLCHAIN_ROOTS", " ".join(roots)),
        ("WEBUI_VUE_NPM_GENERATOR", generator_id()),
    )


def read_inputs(inc_path):
    """Single-line WEBUI_VUE_NPM_* values from an existing .inc, or None."""
    try:
        with open(inc_path, encoding="utf-8") as handle:
            text = handle.read()
    except OSError:
        return None
    return dict(re.findall(r'^(WEBUI_VUE_NPM_\w+) = "([^"\\]*)"$', text, re.M))


def render_inc(packages, inputs):
    shipped = sorted(
        item["pn"] for item in packages if item["role"] == "shipped"
    )
    build = sorted(item["pn"] for item in packages if item["role"] == "build")

    def block(names):
        if not names:
            return '""'
        return '"\\\n    ' + " \\\n    ".join(names) + ' \\\n"'

    lines = [
        HEADER.rstrip("\n"),
        "# WEBUI_VUE_NPM_PACKAGES is the image SBOM set, and",
        "# WEBUI_VUE_NPM_BUILD_PACKAGES is the Vite toolchain required to",
        "# build offline. A bump regenerates these files only when one of",
        "# the values below changes.",
    ]
    lines += ['{} = "{}"'.format(name, value) for name, value in inputs]
    lines += [
        "WEBUI_VUE_NPM_PACKAGES = {}".format(block(shipped)),
        "WEBUI_VUE_NPM_BUILD_PACKAGES = {}".format(block(build)),
    ]
    return "\n".join(lines) + "\n"


def _is_generated(path):
    try:
        with open(path, encoding="utf-8") as handle:
            first = handle.readline()
    except OSError:
        return False
    return first.startswith("# Generated by openbmc-autobump")


def _atomic_write(path, content):
    temporary = os.path.join(
        os.path.dirname(path), "." + os.path.basename(path) + ".tmp"
    )
    with open(temporary, "w", encoding="utf-8") as handle:
        handle.write(content)
    os.replace(temporary, path)


def generate_lock(
    lock,
    lock_bytes,
    outdir,
    common_licenses,
    fetch,
    roots=TOOLCHAIN_ROOTS,
    build_os=DEFAULT_BUILD_OS,
    build_cpu=DEFAULT_BUILD_CPU,
    build_libc=DEFAULT_BUILD_LIBC,
):
    packages = collect_packages(lock, build_os, build_cpu, build_libc, roots)
    for package in packages:
        license_name, license_file, license_bytes = inspect_tarball(
            fetch(package["resolved"]), package["integrity"]
        )
        package["license"] = license_name
        package["license_file"] = license_file
        package["license_bytes"] = license_bytes
    rendered = []
    for package in packages:
        filename = "{}_{}.bb".format(package["pn"], package["version"])
        rendered.append((filename, render_recipe(package, common_licenses)))
    inc = render_inc(
        packages,
        generation_inputs(lock_bytes, roots, build_os, build_cpu, build_libc),
    )
    os.makedirs(outdir, exist_ok=True)
    written = set()
    for filename, content in rendered:
        _atomic_write(os.path.join(outdir, filename), content)
        written.add(filename)
    _atomic_write(os.path.join(outdir, INC_NAME), inc)
    for entry in os.listdir(outdir):
        if not entry.endswith(".bb") or entry in written:
            continue
        path = os.path.join(outdir, entry)
        if _is_generated(path):
            os.remove(path)
    return packages


def generate_recipes(
    lockfile,
    outdir,
    common_licenses,
    fetch=None,
    vite_config=None,
    build_os=DEFAULT_BUILD_OS,
    build_cpu=DEFAULT_BUILD_CPU,
    build_libc=DEFAULT_BUILD_LIBC,
):
    with open(lockfile, "rb") as handle:
        lock_bytes = handle.read()
    lock = json.loads(lock_bytes.decode("utf-8"))
    return generate_lock(
        lock,
        lock_bytes,
        outdir,
        common_licenses,
        fetch or default_fetch,
        roots=toolchain_roots(lock, vite_config),
        build_os=build_os,
        build_cpu=build_cpu,
        build_libc=build_libc,
    )


def update_recipes_for_bump(
    meta,
    recipe,
    lock_bytes,
    common_licenses,
    vite_config=None,
    fetch=None,
    build_os=DEFAULT_BUILD_OS,
    build_cpu=DEFAULT_BUILD_CPU,
    build_libc=DEFAULT_BUILD_LIBC,
):
    """Write recipes next to the webui recipe directory.

    Returns that directory, relative to meta, and whether anything was
    regenerated. Nothing is fetched or written while the existing .inc
    records the same inputs.
    """
    out_rel = npm_recipe_dir(recipe)
    outdir = os.path.join(meta, out_rel)
    lock = json.loads(lock_bytes.decode("utf-8"))
    roots = toolchain_roots(lock, vite_config)
    inputs = generation_inputs(
        lock_bytes, roots, build_os, build_cpu, build_libc
    )
    recorded = read_inputs(os.path.join(outdir, INC_NAME))
    if recorded and all(recorded.get(name) == value for name, value in inputs):
        return out_rel, False
    generate_lock(
        lock,
        lock_bytes,
        outdir,
        common_licenses,
        fetch or default_fetch,
        roots=roots,
        build_os=build_os,
        build_cpu=build_cpu,
        build_libc=build_libc,
    )
    return out_rel, True


def main(argv=None):
    parser = argparse.ArgumentParser(
        description=(
            "Generate webui-vue npm recipes from package-lock.json. "
            "openbmc-autobump does this on each webui-vue SRCREV bump; "
            "run it by hand to try the recipes locally."
        )
    )
    parser.add_argument("lockfile", help="webui-vue package-lock.json")
    parser.add_argument("outdir", help="directory to write the recipes into")
    parser.add_argument(
        "--common-licenses",
        required=True,
        help="oe-core meta/files/common-licenses",
    )
    parser.add_argument(
        "--vite-config",
        help=(
            "vite.config.js whose imports join the toolchain (default: "
            "vite.config.js beside the lockfile, if there is one)"
        ),
    )
    args = parser.parse_args(argv)
    config = args.vite_config
    if config is None:
        beside = os.path.join(
            os.path.dirname(os.path.abspath(args.lockfile)), "vite.config.js"
        )
        config = beside if os.path.isfile(beside) else None
    try:
        vite_config = None
        if config:
            with open(config, encoding="utf-8") as handle:
                vite_config = handle.read()
        packages = generate_recipes(
            args.lockfile,
            args.outdir,
            args.common_licenses,
            vite_config=vite_config,
        )
    except (OSError, ValueError) as error:
        sys.stderr.write("error: {}\n".format(error))
        return 1
    print("wrote {} recipes to {}".format(len(packages), args.outdir))
    return 0


if __name__ == "__main__":
    sys.exit(main())
