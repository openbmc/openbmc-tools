#!/usr/bin/env python3

# Generate Yocto recipes for webui-vue's npm graph.
#
# Shipped packages (the image SBOM) are the non-dev lockfile entries
# reached from webui-vue's dependencies. The Vite build also needs its own
# toolchain, including dev-only entries, or the firmware build cannot drop
# network access. Optional peers are not followed, and platform-specific
# binaries are limited to the OpenBMC build host, linux-x64 with glibc.
#
# openbmc-autobump calls update_recipes_for_bump when it bumps webui-vue.
# Run this file directly to generate the recipes by hand. This module does
# not modify any other recipe.

